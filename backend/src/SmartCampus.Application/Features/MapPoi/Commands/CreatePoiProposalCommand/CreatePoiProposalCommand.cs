using System.Security.Cryptography;
using System.Text.Json;
using FluentValidation;
using MediatR;
using SmartCampus.Application.Common.Abstractions.Messaging;
using SmartCampus.Application.Common.Abstractions.Persistence;
using SmartCampus.Application.Common.Exceptions;
using SmartCampus.Domain.Entities;

namespace SmartCampus.Application.Features.MapPoi;

public sealed record CreatePoiProposalCommand(Guid ActorUserId, CreatePoiProposalRequest Request)
    : IPoiMutationCommand<PoiProposalView>;

public sealed class CreatePoiProposalCommandValidator : AbstractValidator<CreatePoiProposalCommand>
{
    public CreatePoiProposalCommandValidator()
    {
        RuleFor(command => command.Request.RequestId).NotEmpty();
        RuleFor(command => command.Request.Draft.MapVersionId).NotEmpty();
        MapPoiValidationRules.AddDraftRules(RuleFor(command => command.Request.Draft));
    }
}

public sealed class CreatePoiProposalCommandHandler(
    IMapVersionRepository mapRepository,
    IPoiProposalRepository proposalRepository,
    IPoiVerificationRepository verificationRepository,
    IMapPoiRequestLock requestLock,
    IApplicationDbContext dbContext,
    TimeProvider timeProvider)
    : IRequestHandler<CreatePoiProposalCommand, PoiProposalView>
{
    public async Task<PoiProposalView> Handle(CreatePoiProposalCommand command, CancellationToken cancellationToken)
    {
        var draft = MapPoiValidationRules.Normalize(command.Request.Draft);
        var draftHash = MapPoiRequestHash.Compute(draft);
        var requestHash = MapPoiRequestHash.Compute(new { command.Request.RequestId, Draft = draft });
        await requestLock.LockRequestAsync(command.ActorUserId, command.Request.RequestId, "poi-create", cancellationToken);
        var prior = await proposalRepository.FindProposalCreateRequestAsync(command.ActorUserId, command.Request.RequestId, cancellationToken);
        if (prior is not null)
        {
            MapPoiRequestIdempotency.EnsureSameRequest(prior.CreateRequestHash, requestHash);
            return await PoiProposalReadModelLoader.LoadAsync(proposalRepository, verificationRepository, prior,
                await proposalRepository.FindCurrentRevisionAsync(prior.Id, cancellationToken) ?? throw new ConflictException("The proposal has no revision."),
                cancellationToken);
        }

        var map = await mapRepository.FindMapVersionAsync(draft.MapVersionId, includePackage: true, cancellationToken)
            ?? throw new NotFoundException("Map version", draft.MapVersionId);
        await mapRepository.LockMapPreparationStateAsync(map.Id, cancellationToken);
        (await MapPreparationEligibility.LoadAsync(mapRepository, map, cancellationToken)).EnsureCanUse();
        PoiProposalRules.ValidatePosition(map, draft);
        var now = timeProvider.GetUtcNow();
        var proposal = new PoiProposal
        {
            Id = Guid.NewGuid(),
            CreatedByUserId = command.ActorUserId,
            CreateRequestId = command.Request.RequestId,
            CreateRequestHash = requestHash,
            CurrentRevision = 1,
            CreatedAt = now
        };
        var revision = PoiProposalRules.CreateRevision(proposal.Id, 1, command.ActorUserId, command.Request.RequestId, draftHash, draft, now);
        revision.MapVersion = map;
        proposalRepository.Add(proposal);
        proposalRepository.Add(revision);
        proposalRepository.AddAuditLog(new AuditLog
        {
            ActorUserId = command.ActorUserId,
            Action = "POI_PROPOSAL_CREATED",
            EntityType = "PoiProposal",
            EntityId = proposal.Id.ToString("D"),
            ResultCode = "DRAFT",
            DataJson = JsonSerializer.Serialize(new { revision = revision.RevisionNumber, mapVersionId = map.Id, revision.MapVersion.MapKey }),
            OccurredAt = now
        });
        // SQL rowversion is generated by the database; flush inside the surrounding
        // transaction so the returned draft can be safely edited.
        await dbContext.SaveChangesAsync(cancellationToken);
        return await PoiProposalReadModelLoader.LoadAsync(proposalRepository, verificationRepository, proposal, revision, cancellationToken);
    }


}
